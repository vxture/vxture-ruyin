/**
 * 平台目录快照 —— 「热门推荐」的数据来源。
 *
 * **这里为什么可以有静态数据，而「我的产品」永远不可以。**
 *
 * 首页有一条硬规则：不得硬编码产品，因为编造出来的产品会让用户以为自己拥有
 * 并不存在的订阅。这条规则约束的是**所有权表达** —— 「我的产品」那一栏说的是
 * 「你有这些」，它必须完全来自 daemon（订阅状态 + 本地已装运行时），一个字都
 * 不能是本地编的。
 *
 * 「热门推荐」说的是另一句话：「平台上有这些，你可以去看看」。它不声称所有权，
 * 动作只有一个「去平台了解 ↗」的外链，永远没有「打开」。所以它可以有静态数据。
 *
 * 但**静态不等于可以编**。下面每一条都是 2026-09-02 从
 * https://vxture.com/zh-CN/appcenter 真实目录逐字抄下来的：名称、分类、状态、
 * 简介、能力标签都取自那一页，不是我拟的。`status` 照实保留「开发中」——把
 * 未上线的写成可订阅，和编造产品是同一类错误。
 *
 * 这是**过渡态**：平台还没有给桌面端可达的目录端点，接上之后这个文件整体删掉，
 * 换成一次 fetch。在那之前，宁可用一份有出处、可核对的快照，也不用一份编的。
 */

export interface CatalogEntry {
  /** 平台目录里的分类标签，如「数字员工 · 通用类」。 */
  category: string;
  name: string;
  /** 照实保留：已上线才是 `released`，其余一律 `building`。 */
  status: "released" | "building";
  /** 仅已上线的条目有版本号；开发中的没有，也不能编一个。 */
  version?: string;
  summary: string;
  /** 平台页上列出的能力标签，最多三个。 */
  capabilities: string[];
}

